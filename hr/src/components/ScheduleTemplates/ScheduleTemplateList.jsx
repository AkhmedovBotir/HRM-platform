import { motion } from 'framer-motion'
import ScheduleTemplateCard from './ScheduleTemplateCard'

function ScheduleTemplateList({ templates, onEdit, onDeleteClick, onStatusChange, loading }) {
  if (loading) {
    return (
      <div className="flex justify-center items-center py-12">
        <div className="animate-spin rounded-full h-12 w-12 border-b-2 border-blue-600"></div>
      </div>
    )
  }

  if (!templates || templates.length === 0) {
    return (
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        className="text-center py-12 bg-white rounded-lg shadow-sm"
      >
        <svg className="mx-auto h-12 w-12 text-gray-400" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M9 5H7a2 2 0 00-2 2v12a2 2 0 002 2h10a2 2 0 002-2V7a2 2 0 00-2-2h-2M9 5a2 2 0 002 2h2a2 2 0 002-2M9 5a2 2 0 012-2h2a2 2 0 012 2" />
        </svg>
        <h3 className="mt-2 text-sm font-medium text-gray-900">Shablonlar topilmadi</h3>
        <p className="mt-1 text-sm text-gray-500">Yangi shablon qo'shish uchun "Yangi shablon" tugmasini bosing.</p>
      </motion.div>
    )
  }

  return (
    <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
      {templates.map((template, index) => (
        <motion.div
          key={template.id}
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: index * 0.1 }}
        >
          <ScheduleTemplateCard
            template={template}
            onEdit={onEdit}
            onDeleteClick={onDeleteClick}
            onStatusChange={onStatusChange}
          />
        </motion.div>
      ))}
    </div>
  )
}

export default ScheduleTemplateList






